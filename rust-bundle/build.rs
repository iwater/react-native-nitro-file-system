extern crate cbindgen;

use std::env;
use std::path::PathBuf;

fn main() {
    let crate_dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    let package_name = env::var("CARGO_PKG_NAME").unwrap();

    // Generate C header
    let target_dir = PathBuf::from(crate_dir.clone()).join("include");
    std::fs::create_dir_all(&target_dir).unwrap();

    let output_file = target_dir.join("rust_c_file_system.h");

    cbindgen::Builder::new()
        .with_crate(crate_dir)
        .with_language(cbindgen::Language::C)
        .with_header("/* Code generated by cbindgen. DO NOT EDIT. */\n\n#ifndef RUST_C_FILE_SYSTEM_H\n#define RUST_C_FILE_SYSTEM_H")
        .with_language(cbindgen::Language::C)
        .with_autogen_warning("") // Already included in header
        .with_after_include("#ifdef __cplusplus\nextern \"C\" {\n#endif")
        .with_trailer("#ifdef __cplusplus\n}\n#endif\n\n#endif /* RUST_C_FILE_SYSTEM_H */")
        .generate()
        .expect("Unable to generate bindings")
        .write_to_file(output_file);
        
    // Trigger rebuild if source changes
    println!("cargo:rerun-if-changed=src/lib.rs");
}
